window.lang = (function() {
  try { return localStorage.getItem("qa-board-lang") === "zh" ? "zh" : "en"; } catch (e) { return "en"; }
})();
window.t = function(k, vars) {
  const pack = (window.I18N[window.lang] || window.I18N.en);
  let s = pack[k];
  if (s == null) s = window.I18N.en[k];
  if (s == null) return k;
  if (vars) Object.keys(vars).forEach(key => { s = String(s).replace("{" + key + "}", vars[key]); });
  return s;
};
window.tType = function(type) {
  const k = String(type || "").toLowerCase();
  if (k === "inline") return window.t("inline");
  if (k === "final") return window.t("final");
  if (k === "sourcing") return window.t("sourcing");
  if (k === "audit") return window.t("audit");
  if (k === "leave") return window.t("annualLeave");
  return type;
};
window.tCountry = function(code) {
  const map = { IN: "india", CN: "china", VN: "vietnam", TH: "thailand", KH: "cambodia", MY: "malaysia", ID: "indonesia" };
  return map[code] ? window.t(map[code]) : code;
};
window.setLang = function(next) {
  window.lang = next === "zh" ? "zh" : "en";
  try { localStorage.setItem("qa-board-lang", window.lang); } catch (e) {}
  document.documentElement.lang = window.lang === "zh" ? "zh-CN" : "en";
};
